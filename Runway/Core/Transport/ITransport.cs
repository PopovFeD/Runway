namespace Runway.Transport;

// Общий интерфейс канала доставки байт от устройства к приложению, независимо
// от физической природы канала (COM-порт сейчас, WiFi/TCP для ESP32 — в будущем).
// Слои выше (ViewModel, Framing) работают только с ним и не знают, что именно
// находится на другом конце.
//
// "Endpoint" — строка-адрес конкретной точки подключения в терминах транспорта:
// у Serial это имя порта ("COM6", "/dev/ttyUSB0"), у WiFi будет "192.168.1.42:3333".
// Остальная конфигурация, специфичная для транспорта (скорость порта и т.п.),
// задаётся при создании конкретной реализации, а не через этот интерфейс.
public interface ITransport
{
    // Имя для списка транспортов в GUI ("Serial (COM)", "WiFi (ESP32)")
    string DisplayName { get; }

    bool IsOpen { get; }

    // Какие точки подключения видны прямо сейчас: список COM-портов в системе,
    // в будущем — обнаруженные в сети устройства. Может быть пустым — тогда
    // подключаться не к чему и GUI не даёт нажать "Подключить".
    IReadOnlyList<string> GetAvailableEndpoints();

    void Open(string endpoint);
    void Close();

    // Вызывается каждый раз, когда пришли новые байты из канала.
    // ВАЖНО: событие приходит из фонового потока транспорта, не из UI-потока.
    event Action<byte[]>? DataReceived;

    // Вызывается при смене состояния подключения: разрыв, попытка
    // переподключения, успешное (пере-)подключение. Нужно, чтобы GUI могло
    // показать пользователю, что связь разорвана, не парся текст лога.
    event Action<ConnectionState>? ConnectionStateChanged;
}
